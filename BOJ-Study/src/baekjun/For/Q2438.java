package baekjun.For;

import java.util.Scanner;

public class Q2438 {

	/*
	 * 
	 * *
	 * * *
	 * * * * 
	 * * * * * 
	 */ 
	
	public static void main(String[] args) {
		
		Scanner scan = new Scanner(System.in);
		int line = scan.nextInt();
		
		
		for ( int i = 0 ; i < line ; i++) {  
			
			for ( int j = 0 ; j <= 0 ; j++) {  
				
				System.out.print("*");
				
			}
			System.out.println(" ");
			
		}
	}
	
	
}
